function buildDesGuideChapters(): OriginChapter[] {
  const raw = desGuideCiel as {
    sections?: { title?: string; lines?: string[] }[];
    exampleTable?: { columns?: string[]; rows?: string[][] };
    lines?: string[];
  };
  const chapters: OriginChapter[] = [];
  for (const sec of raw.sections ?? []) {
    const title = String(sec.title ?? "").trim() || "안내";
    const blocks = (sec.lines ?? [])
      .map((line) => String(line).trim())
      .filter(Boolean)
      .map((text) => p(text));
    if (blocks.length) chapters.push({ title, blocks });
  }
  const table = raw.exampleTable;
  if (table?.columns?.length && table.rows?.length) {
    chapters.push({
      title: "3. 항목별 작성요령·작성예",
      blocks: [
        {
          kind: "table",
          headers: table.columns.map(String),
          rows: table.rows.map((row) => row.map((cell) => String(cell ?? ""))),
        },
      ],
    });
  }
  if (!chapters.length && Array.isArray(raw.lines)) {
    chapters.push({
      title: "품명·규격 작성 가이드라인",
      blocks: raw.lines.map((line) => String(line).trim()).filter(Boolean).map((text) => p(text)),
    });
  }
  return chapters;
}

